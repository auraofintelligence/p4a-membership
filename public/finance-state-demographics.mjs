function censusLink(censusSource, districtName) {
  if (censusSource !== 'WA') return censusSources[censusSource];
  const district = districtName.toLowerCase().replace(/[ -]+/g, '%2B');
  const file = `ep%2B2025%2B${district}%2Bfull%2Bdoc`;
  return `https://www.parliament.wa.gov.au/intranet/libpages.nsf/WebFiles/${file}/%24FILE/${file}.pdf`;
}

